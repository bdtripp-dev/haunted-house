package com.bdtripp.hauntedhouse.model;

/**
 * Enumerates all supported room names.
 *
 * @author Brian Tripp
 */
public enum RoomName {

    /** A hallway in the house. */
    HALLWAY,

    /** A study room. */
    STUDY,

    /** An indoor garden area. */
    INDOOR_GARDEN,

    /** A storage cellar. */
    ROOT_CELLAR,

    /** The library. */
    LIBRARY,

    /** A billiard room. */
    BILLIARD_ROOM,

    /** A den. */
    DEN,

    /** A wine storage cellar. */
    WINE_CELLAR,

    /** A bathroom. */
    BATHROOM,

    /** The area outside the house. */
    OUTSIDE
}
